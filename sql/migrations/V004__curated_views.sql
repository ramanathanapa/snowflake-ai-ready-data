-- Typed, conformed layer over RAW. Views (not Dynamic Tables): data is ~170K rows, so no refresh cost.
-- ponytail: switch to Dynamic Tables if volume grows past what a view recomputes cheaply.
USE ROLE FUND_ENGINEER;
USE DATABASE FUND_AI;
USE SCHEMA CURATED;

-- one row per share class of each tracked series
CREATE OR REPLACE VIEW DIM_FUND_CLASS AS
SELECT SERIES_ID, CLASS_ID, UPPER(SYMBOL) AS TICKER, CIK
FROM RAW.SEC_FUND_TICKERS;

-- one row per fund (series); tickers = all classes
CREATE OR REPLACE VIEW DIM_FUND AS
SELECT i.SERIES_ID,
       ANY_VALUE(i.SERIES_NAME)                              AS SERIES_NAME,
       ANY_VALUE(r.REGISTRANT_NAME)                          AS REGISTRANT_NAME,
       ANY_VALUE(r.CIK)                                      AS CIK,
       (SELECT LISTAGG(DISTINCT TICKER, ', ') WITHIN GROUP (ORDER BY TICKER)
          FROM DIM_FUND_CLASS c WHERE c.SERIES_ID = i.SERIES_ID) AS TICKERS,
       -- ETFs have 3-4 letters, mutual funds 5: shortest ticker is the recognisable one
       (SELECT MIN_BY(TICKER, LPAD(LENGTH(TICKER), 2, '0') || TICKER)
          FROM DIM_FUND_CLASS c WHERE c.SERIES_ID = i.SERIES_ID) AS PRIMARY_TICKER
FROM RAW.NPORT_FUND_REPORTED_INFO i
JOIN RAW.NPORT_REGISTRANT r USING (ACCESSION_NUMBER)
GROUP BY i.SERIES_ID;

-- one row per filing (fund x as-of date)
CREATE OR REPLACE VIEW FUND_FILING AS
SELECT i.ACCESSION_NUMBER,
       i.SERIES_ID,
       TO_DATE(s.REPORT_DATE, 'DD-MON-YYYY')  AS REPORT_DATE,   -- portfolio as-of date
       TO_DATE(s.FILING_DATE, 'DD-MON-YYYY')  AS FILING_DATE,   -- when public (use for point-in-time)
       TRY_TO_NUMBER(i.TOTAL_ASSETS, 38, 2)       AS TOTAL_ASSETS,
       TRY_TO_NUMBER(i.TOTAL_LIABILITIES, 38, 2)  AS TOTAL_LIABILITIES,
       TRY_TO_NUMBER(i.NET_ASSETS, 38, 2)         AS NET_ASSETS,
       s.SUB_TYPE
FROM RAW.NPORT_FUND_REPORTED_INFO i
JOIN RAW.NPORT_SUBMISSION s USING (ACCESSION_NUMBER);

-- one row per holding per filing
CREATE OR REPLACE VIEW FUND_HOLDING AS
SELECT h.ACCESSION_NUMBER,
       h.HOLDING_ID,
       f.SERIES_ID,
       f.REPORT_DATE,
       h.ISSUER_NAME,
       h.ISSUER_TITLE,
       IFF(h.ISSUER_CUSIP IN ('000000000', 'N/A', ''), NULL, h.ISSUER_CUSIP) AS CUSIP,  -- placeholders are not identifiers
       id.IDENTIFIER_ISIN                       AS ISIN,
       id.IDENTIFIER_TICKER                     AS TICKER,
       h.ASSET_CAT,
       h.ISSUER_TYPE,
       h.INVESTMENT_COUNTRY                     AS COUNTRY,
       h.PAYOFF_PROFILE,
       h.CURRENCY_CODE,
       TRY_TO_DOUBLE(h.BALANCE)                 AS BALANCE,
       h.UNIT,
       TRY_TO_NUMBER(h.CURRENCY_VALUE, 38, 2)   AS VALUE_USD,
       TRY_TO_DOUBLE(h.PERCENTAGE)              AS PCT_NET_ASSETS,
       d.COUPON_TYPE,
       TRY_TO_DOUBLE(d.ANNUALIZED_RATE)         AS COUPON_RATE,
       TO_DATE(d.MATURITY_DATE, 'DD-MON-YYYY')  AS MATURITY_DATE,
       -- identity of the security across funds and filings (same stock/bond => same key)
       COALESCE(IFF(h.ISSUER_CUSIP IN ('000000000', 'N/A', ''), NULL, h.ISSUER_CUSIP), NULLIF(id.IDENTIFIER_ISIN, 'N/A'),
                UPPER(h.ISSUER_NAME || '|' || COALESCE(h.ISSUER_TITLE, ''))) AS SECURITY_KEY
FROM RAW.NPORT_FUND_REPORTED_HOLDING h
JOIN FUND_FILING f USING (ACCESSION_NUMBER)
LEFT JOIN (SELECT HOLDING_ID, MAX(IDENTIFIER_ISIN) AS IDENTIFIER_ISIN, MAX(IDENTIFIER_TICKER) AS IDENTIFIER_TICKER
           FROM RAW.NPORT_IDENTIFIERS GROUP BY HOLDING_ID) id USING (HOLDING_ID)  -- several id rows per holding
LEFT JOIN RAW.NPORT_DEBT_SECURITY d USING (HOLDING_ID);

-- monthly total return (%) per share class: 3 months per filing; REPORT_DATE is the 3rd month
CREATE OR REPLACE VIEW FUND_RETURN_MONTHLY AS
SELECT f.SERIES_ID, m.CLASS_ID, c.TICKER,
       LAST_DAY(DATEADD(month, u.INDEX - 2, f.REPORT_DATE)) AS MONTH_END,
       TRY_TO_DOUBLE(u.VALUE::STRING)                       AS TOTAL_RETURN_PCT
FROM RAW.NPORT_MONTHLY_TOTAL_RETURN m
JOIN FUND_FILING f USING (ACCESSION_NUMBER)
LEFT JOIN DIM_FUND_CLASS c ON c.CLASS_ID = m.CLASS_ID,
LATERAL FLATTEN(INPUT => ARRAY_CONSTRUCT(m.MONTHLY_TOTAL_RETURN1, m.MONTHLY_TOTAL_RETURN2, m.MONTHLY_TOTAL_RETURN3)) u;

-- interest-rate sensitivity per filing (bond funds): DV01 = $ change per 1bp, by tenor
CREATE OR REPLACE VIEW FUND_RATE_RISK AS
SELECT f.SERIES_ID, f.REPORT_DATE, r.CURRENCY_CODE,
       TRY_TO_DOUBLE(r.INTRST_RATE_CHANGE_3MON_DV01)  AS DV01_3M,
       TRY_TO_DOUBLE(r.INTRST_RATE_CHANGE_1YR_DV01)   AS DV01_1Y,
       TRY_TO_DOUBLE(r.INTRST_RATE_CHANGE_5YR_DV01)   AS DV01_5Y,
       TRY_TO_DOUBLE(r.INTRST_RATE_CHANGE_10YR_DV01)  AS DV01_10Y,
       TRY_TO_DOUBLE(r.INTRST_RATE_CHANGE_30YR_DV01)  AS DV01_30Y
FROM RAW.NPORT_INTEREST_RATE_RISK r
JOIN FUND_FILING f USING (ACCESSION_NUMBER);
