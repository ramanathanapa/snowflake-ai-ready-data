-- ANALYTICS: PM-facing views, one question-shape each. This is what the semantic view / Cortex Analyst sits on.
-- "Latest" = most recent filing LOADED for each fund. As-of dates differ per fund and are always exposed.
USE ROLE FUND_ENGINEER;
USE DATABASE FUND_AI;
USE SCHEMA ANALYTICS;

-- each fund's latest snapshot, with how stale it is
CREATE OR REPLACE VIEW LATEST_FILING AS
SELECT f.SERIES_ID, d.PRIMARY_TICKER, d.SERIES_NAME, d.TICKERS, f.ACCESSION_NUMBER,
       f.REPORT_DATE AS AS_OF_DATE, f.FILING_DATE, f.NET_ASSETS,
       DATEDIFF(day, f.REPORT_DATE, CURRENT_DATE()) AS DAYS_SINCE_AS_OF
FROM CURATED.FUND_FILING f
JOIN CURATED.DIM_FUND d USING (SERIES_ID)
QUALIFY ROW_NUMBER() OVER (PARTITION BY f.SERIES_ID ORDER BY f.REPORT_DATE DESC) = 1;

-- every position of every fund's latest snapshot, with readable names
CREATE OR REPLACE VIEW LATEST_HOLDING AS
SELECT l.SERIES_ID, l.PRIMARY_TICKER AS FUND_TICKER, l.SERIES_NAME AS FUND_NAME, l.AS_OF_DATE,
       h.HOLDING_ID, h.SECURITY_KEY, h.ISSUER_NAME, h.ISSUER_TITLE, h.CUSIP, h.ISIN, h.TICKER AS SECURITY_TICKER,
       h.ASSET_CAT, a.ASSET_CLASS, h.ISSUER_TYPE, i.ISSUER_CATEGORY, h.COUNTRY, h.CURRENCY_CODE, h.PAYOFF_PROFILE,
       h.VALUE_USD, h.PCT_NET_ASSETS, h.COUPON_TYPE, h.COUPON_RATE, h.MATURITY_DATE,
       DATEDIFF(day, l.AS_OF_DATE, h.MATURITY_DATE) / 365.25 AS YEARS_TO_MATURITY
FROM CURATED.FUND_HOLDING h
JOIN LATEST_FILING l ON l.ACCESSION_NUMBER = h.ACCESSION_NUMBER
LEFT JOIN CURATED.DIM_ASSET_CATEGORY a ON a.ASSET_CAT = h.ASSET_CAT
LEFT JOIN CURATED.DIM_ISSUER_TYPE   i ON i.ISSUER_TYPE = h.ISSUER_TYPE;

-- one row per fund: the "fund card" a PM scans first
CREATE OR REPLACE VIEW FUND_SUMMARY AS
WITH mix AS (
  SELECT SERIES_ID,
         COUNT(*)                                                                    AS POSITIONS,
         SUM(IFF(ASSET_CAT IN ('EC','EP'), PCT_NET_ASSETS, 0))                       AS EQUITY_PCT,
         SUM(IFF(ASSET_CAT IN ('DBT','ABS-MBS','ABS-CBDO','ABS-APCP','ABS-O','LON','SN'), PCT_NET_ASSETS, 0)) AS DEBT_PCT
  FROM LATEST_HOLDING GROUP BY SERIES_ID
), top10 AS (
  SELECT SERIES_ID, SUM(PCT) AS TOP10_PCT FROM (
    SELECT SERIES_ID, SUM(PCT_NET_ASSETS) AS PCT,
           ROW_NUMBER() OVER (PARTITION BY SERIES_ID ORDER BY SUM(PCT_NET_ASSETS) DESC) AS rn
    FROM LATEST_HOLDING GROUP BY SERIES_ID, SECURITY_KEY
  ) WHERE rn <= 10 GROUP BY SERIES_ID
), ret AS (
  SELECT SERIES_ID, TICKER, CALENDAR_YEAR, TOTAL_RETURN_PCT FROM CURATED.FUND_ANNUAL_RETURN
  QUALIFY ROW_NUMBER() OVER (PARTITION BY SERIES_ID, TICKER ORDER BY CALENDAR_YEAR DESC) = 1
)
SELECT l.SERIES_ID, l.PRIMARY_TICKER AS FUND_TICKER, l.SERIES_NAME AS FUND_NAME, l.TICKERS AS ALL_TICKERS,
       r.REGISTRANT_NAME AS FUND_FAMILY,
       l.NET_ASSETS, l.AS_OF_DATE, l.FILING_DATE, l.DAYS_SINCE_AS_OF,
       CASE WHEN m.EQUITY_PCT >= 70 THEN 'Equity' WHEN m.DEBT_PCT >= 70 THEN 'Fixed income' ELSE 'Mixed / other' END AS FUND_TYPE,
       m.POSITIONS, m.EQUITY_PCT, m.DEBT_PCT, t.TOP10_PCT AS TOP10_CONCENTRATION_PCT,
       fe.EXPENSE_RATIO_PCT, fe.MANAGEMENT_FEE_PCT,
       tu.TURNOVER_PCT,
       ret.CALENDAR_YEAR AS LAST_FULL_YEAR, ret.TOTAL_RETURN_PCT AS LAST_FULL_YEAR_RETURN_PCT
FROM LATEST_FILING l
JOIN CURATED.DIM_FUND r USING (SERIES_ID)
LEFT JOIN mix m USING (SERIES_ID)
LEFT JOIN top10 t USING (SERIES_ID)
LEFT JOIN CURATED.FUND_FEES fe ON fe.SERIES_ID = l.SERIES_ID AND fe.TICKER = l.PRIMARY_TICKER
LEFT JOIN CURATED.FUND_TURNOVER tu ON tu.SERIES_ID = l.SERIES_ID
LEFT JOIN ret ON ret.SERIES_ID = l.SERIES_ID AND ret.TICKER = l.PRIMARY_TICKER;

-- cost comparison at share-class level
CREATE OR REPLACE VIEW FUND_CLASS_COST AS
SELECT f.TICKER AS CLASS_TICKER, d.PRIMARY_TICKER AS FUND_TICKER, d.SERIES_NAME AS FUND_NAME, s.FUND_TYPE,
       f.EXPENSE_RATIO_PCT, f.MANAGEMENT_FEE_PCT, f.FEE_12B1_PCT, f.OTHER_EXPENSES_PCT, f.MAX_FRONT_LOAD_PCT,
       f.COST_OF_10K_1Y_USD, f.COST_OF_10K_10Y_USD, f.FILED_DATE AS FEES_FILED_DATE
FROM CURATED.FUND_FEES f
JOIN CURATED.DIM_FUND d USING (SERIES_ID)
LEFT JOIN FUND_SUMMARY s USING (SERIES_ID);

-- pairwise overlap of two funds' latest portfolios: sum over shared securities of the smaller weight
-- (100% = identical portfolios). Both directions are present so either fund can be asked about first.
CREATE OR REPLACE VIEW FUND_OVERLAP AS
WITH w AS (
  SELECT SERIES_ID, FUND_TICKER, AS_OF_DATE, SECURITY_KEY, SUM(GREATEST(PCT_NET_ASSETS, 0)) AS W
  FROM LATEST_HOLDING GROUP BY SERIES_ID, FUND_TICKER, AS_OF_DATE, SECURITY_KEY
), pairs AS (
  SELECT a.FUND_TICKER AS FUND_A, b.FUND_TICKER AS FUND_B, a.AS_OF_DATE AS FUND_A_AS_OF, b.AS_OF_DATE AS FUND_B_AS_OF,
         SUM(LEAST(a.W, b.W)) AS OVERLAP_PCT, COUNT(*) AS COMMON_SECURITIES
  FROM w a JOIN w b ON a.SECURITY_KEY = b.SECURITY_KEY AND a.SERIES_ID < b.SERIES_ID
  GROUP BY 1, 2, 3, 4
)
SELECT * FROM pairs
UNION ALL
SELECT FUND_B, FUND_A, FUND_B_AS_OF, FUND_A_AS_OF, OVERLAP_PCT, COMMON_SECURITIES FROM pairs;

-- what changed between each fund's two most recent snapshots (by position).
-- Share counts of ALL holdings of an index fund move together when units are created/redeemed, so a position's
-- change is measured relative to the fund's median change (FUND_FLOW_PCT): INCREASED/DECREASED mean traded
-- more/less than the rest of the portfolio. Weights also drift with prices, so weight change is shown but not used to label.
CREATE OR REPLACE VIEW HOLDING_CHANGES AS
WITH ranked AS (
  SELECT *, DENSE_RANK() OVER (PARTITION BY SERIES_ID ORDER BY REPORT_DATE DESC) AS rk FROM CURATED.FUND_POSITION
), dates AS (
  SELECT SERIES_ID, MAX(IFF(rk = 1, REPORT_DATE, NULL)) AS CURRENT_AS_OF, MAX(IFF(rk = 2, REPORT_DATE, NULL)) AS PREVIOUS_AS_OF
  FROM ranked GROUP BY SERIES_ID
), cur AS (SELECT * FROM ranked WHERE rk = 1), prev AS (SELECT * FROM ranked WHERE rk = 2),
j AS (
  SELECT COALESCE(cur.SERIES_ID, prev.SERIES_ID)       AS SERIES_ID,
         COALESCE(cur.SECURITY_KEY, prev.SECURITY_KEY) AS SECURITY_KEY,
         COALESCE(cur.ISSUER_NAME, prev.ISSUER_NAME)   AS ISSUER_NAME,
         COALESCE(cur.ISSUER_TITLE, prev.ISSUER_TITLE) AS ISSUER_TITLE,
         COALESCE(cur.ASSET_CAT, prev.ASSET_CAT)       AS ASSET_CAT,
         prev.PCT_NET_ASSETS AS PREVIOUS_PCT, cur.PCT_NET_ASSETS AS CURRENT_PCT,
         prev.BALANCE AS PREVIOUS_BALANCE, cur.BALANCE AS CURRENT_BALANCE,
         cur.BALANCE / NULLIF(prev.BALANCE, 0)         AS RATIO,
         prev.SECURITY_KEY IS NULL                     AS IS_NEW,
         cur.SECURITY_KEY  IS NULL                     AS IS_SOLD
  FROM cur FULL OUTER JOIN prev ON cur.SERIES_ID = prev.SERIES_ID AND cur.SECURITY_KEY = prev.SECURITY_KEY
), flow AS (
  SELECT SERIES_ID, MEDIAN(RATIO) AS MEDIAN_RATIO FROM j WHERE RATIO IS NOT NULL GROUP BY SERIES_ID
)
SELECT j.SERIES_ID, d.PRIMARY_TICKER AS FUND_TICKER, dt.CURRENT_AS_OF, dt.PREVIOUS_AS_OF,
       j.SECURITY_KEY, j.ISSUER_NAME, j.ISSUER_TITLE, j.ASSET_CAT,
       j.PREVIOUS_PCT, j.CURRENT_PCT, COALESCE(j.CURRENT_PCT, 0) - COALESCE(j.PREVIOUS_PCT, 0) AS WEIGHT_CHANGE_PTS,
       j.PREVIOUS_BALANCE, j.CURRENT_BALANCE,
       (j.RATIO - 1) * 100                              AS BALANCE_CHANGE_PCT,
       (f.MEDIAN_RATIO - 1) * 100                       AS FUND_FLOW_PCT,
       (j.RATIO / NULLIF(f.MEDIAN_RATIO, 0) - 1) * 100  AS RELATIVE_BALANCE_CHANGE_PCT,
       CASE WHEN j.IS_NEW  THEN 'NEW'
            WHEN j.IS_SOLD THEN 'SOLD'
            WHEN j.RATIO / NULLIF(f.MEDIAN_RATIO, 0) > 1.01 THEN 'INCREASED'
            WHEN j.RATIO / NULLIF(f.MEDIAN_RATIO, 0) < 0.99 THEN 'DECREASED'
            ELSE 'UNCHANGED' END                        AS CHANGE_TYPE
FROM j
LEFT JOIN flow f USING (SERIES_ID)
JOIN dates dt ON dt.SERIES_ID = j.SERIES_ID
JOIN CURATED.DIM_FUND d ON d.SERIES_ID = j.SERIES_ID
WHERE dt.PREVIOUS_AS_OF IS NOT NULL;

-- mix by asset class and by country (latest)
CREATE OR REPLACE VIEW FUND_ASSET_MIX AS
SELECT FUND_TICKER, FUND_NAME, AS_OF_DATE, ASSET_CAT, ASSET_CLASS,
       COUNT(*) AS POSITIONS, SUM(PCT_NET_ASSETS) AS PCT_NET_ASSETS, SUM(VALUE_USD) AS VALUE_USD
FROM LATEST_HOLDING GROUP BY 1, 2, 3, 4, 5;

CREATE OR REPLACE VIEW FUND_COUNTRY_MIX AS
SELECT FUND_TICKER, FUND_NAME, AS_OF_DATE, COALESCE(COUNTRY, 'Unknown') AS COUNTRY,
       COUNT(*) AS POSITIONS, SUM(PCT_NET_ASSETS) AS PCT_NET_ASSETS, SUM(VALUE_USD) AS VALUE_USD
FROM LATEST_HOLDING GROUP BY 1, 2, 3, 4;

-- bond funds: coupon, maturity and rate sensitivity. Duration = |total DV01| / (net assets x 1bp).
-- DV01 sign convention differs by filer (Vanguard reports negative, iShares positive), so duration uses the absolute total;
-- the per-tenor DV01 columns stay as filed. Long-only bond funds assumed; N-PORT DV01 can differ from fund-published duration.
CREATE OR REPLACE VIEW BOND_PROFILE AS
WITH b AS (
  SELECT SERIES_ID, FUND_TICKER, FUND_NAME, AS_OF_DATE,
         SUM(PCT_NET_ASSETS) AS DEBT_PCT,
         SUM(IFF(COUPON_RATE IS NOT NULL, PCT_NET_ASSETS * COUPON_RATE, 0)) / NULLIF(SUM(IFF(COUPON_RATE IS NOT NULL, PCT_NET_ASSETS, 0)), 0) AS WAVG_COUPON_PCT,
         SUM(IFF(MATURITY_DATE IS NOT NULL, PCT_NET_ASSETS * YEARS_TO_MATURITY, 0)) / NULLIF(SUM(IFF(MATURITY_DATE IS NOT NULL, PCT_NET_ASSETS, 0)), 0) AS WAVG_MATURITY_YEARS,
         SUM(IFF(ISSUER_TYPE = 'UST',  PCT_NET_ASSETS, 0)) AS TREASURY_PCT,
         SUM(IFF(ISSUER_TYPE = 'CORP', PCT_NET_ASSETS, 0)) AS CORPORATE_PCT,
         SUM(IFF(ASSET_CAT LIKE 'ABS-%', PCT_NET_ASSETS, 0)) AS SECURITIZED_PCT
  FROM LATEST_HOLDING
  WHERE ASSET_CAT IN ('DBT','ABS-MBS','ABS-CBDO','ABS-APCP','ABS-O','LON','SN')
  GROUP BY 1, 2, 3, 4
  HAVING SUM(PCT_NET_ASSETS) >= 20
)
SELECT b.*, r.DV01_1Y, r.DV01_5Y, r.DV01_10Y, r.DV01_30Y,
       (COALESCE(r.DV01_3M,0) + COALESCE(r.DV01_1Y,0) + COALESCE(r.DV01_5Y,0) + COALESCE(r.DV01_10Y,0) + COALESCE(r.DV01_30Y,0)) AS DV01_TOTAL,
       ABS(COALESCE(r.DV01_3M,0) + COALESCE(r.DV01_1Y,0) + COALESCE(r.DV01_5Y,0) + COALESCE(r.DV01_10Y,0) + COALESCE(r.DV01_30Y,0))
         / NULLIF(l.NET_ASSETS * 0.0001, 0)                                                                                      AS EFFECTIVE_DURATION_YEARS
FROM b
JOIN LATEST_FILING l USING (SERIES_ID)
LEFT JOIN CURATED.FUND_RATE_RISK r ON r.SERIES_ID = b.SERIES_ID AND r.REPORT_DATE = b.AS_OF_DATE;

-- performance, with fund names attached
CREATE OR REPLACE VIEW ANNUAL_RETURNS AS
SELECT r.TICKER AS CLASS_TICKER, d.PRIMARY_TICKER AS FUND_TICKER, d.SERIES_NAME AS FUND_NAME, r.CALENDAR_YEAR, r.TOTAL_RETURN_PCT
FROM CURATED.FUND_ANNUAL_RETURN r JOIN CURATED.DIM_FUND d USING (SERIES_ID);

CREATE OR REPLACE VIEW MONTHLY_RETURNS AS
SELECT r.TICKER AS CLASS_TICKER, d.PRIMARY_TICKER AS FUND_TICKER, d.SERIES_NAME AS FUND_NAME, r.MONTH_END, r.TOTAL_RETURN_PCT
FROM CURATED.FUND_RETURN_MONTHLY r JOIN CURATED.DIM_FUND d USING (SERIES_ID);
